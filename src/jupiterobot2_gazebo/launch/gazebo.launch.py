"""Gazebo simulation for Jupiter 2: world + robot + controllers.

WHY THIS FILE IS MORE THAN A Node() LIST
----------------------------------------
gazebo_ros2_control's plugin has two ways to find the URDF:

  a) <robot_param>robot_description</robot_param>
     <robot_param_node>robot_state_publisher</robot_param_node>
     It reads the param, then re-passes it as a CLI override:
         --param robot_description:=<?xml version="1.0" ?>
     The rcl YAML parser rejects that string, because URDF attribute colons
     ("joint name=") are not valid YAML. The plugin fails with
         parser error Couldn't parse parameter override rule
     the controller manager is never created, /joint_states stays silent, and
     the launch STILL reports success. That was the state of this repo.

  b) No robot_param tags: the plugin reads robot_description out of its
     <parameters> YAML file, which is valid YAML by construction.

This launch file takes route (b). It expands the URDF itself, writes a merged
parameters file (controllers + robot_description) into the build tree, and
points the plugin at it. The URDF therefore only has to be valid XML, never
valid YAML.
"""

import os
import re
import subprocess
import tempfile

from launch import LaunchDescription
from launch.actions import (DeclareLaunchArgument, ExecuteProcess,
                            SetEnvironmentVariable, TimerAction)
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
from ament_index_python.packages import (get_package_prefix,
                                         get_package_share_directory)

ROBOT_STATE_TOPIC = "/robot_description"

# Loaded in this order. joint_state_broadcaster first so /joint_states exists
# before any trajectory controller starts publishing commands.
CONTROLLERS = ("joint_state_broadcaster", "head_group_controller",
               "arm_group_controller", "gripper_group_controller")

# Gazebo takes ~10-15 s to finish loading the world and spawn the model before
# gazebo_ros2_control creates /controller_manager. Spawning earlier makes every
# spawner give up with "Could not contact service" and silently load nothing.
SPAWNER_DELAY_S = 20.0


def _build_model_path(desc_share, desc_prefix):
    parts = [os.path.join(desc_share, "models"),
             os.path.join(desc_prefix, "share")]
    for pkg in ("jupiterobot2_head_description", "so100_description"):
        try:
            parts.append(os.path.join(get_package_prefix(pkg), "share"))
        except Exception:                            # noqa: BLE001
            pass
    return os.pathsep.join(parts)


def _expand_urdf(urdf_path):
    """Expand the xacro and strip XML comments.

    THE COMMENT STRIPPING IS LOAD-BEARING. gazebo_ros2_control reads the URDF
    from the parameter server and re-passes the whole document to rcl as a
    single override, "param robot_description:=<URDF>". rcl parses that value
    as YAML, and a URDF is only valid YAML if it contains no colons outside
    tags -- but xacro emits an autogenerated header comment containing ':' and
    '|', and this project's own xacros had prose comments with colons too.

    The result was:
        parser error Couldn't parse parameter override rule
    after which the controller manager is never created, /joint_states is
    silent and no controller can load -- while the launch still reports
    success. Verified: with comments stripped the same document parses as
    YAML in both single-line and multi-line form.
    """
    raw = subprocess.check_output(
        ["xacro", urdf_path, "use_gazebo:=true"]).decode()
    return re.sub(r"<!--.*?-->", "", raw, flags=re.S)


def _write_params_with_urdf_placeholder(controllers_yaml):
    """Create the temp params file (controllers only), return its path.

    The URDF is filled in afterwards by _fill_urdf_into_params, after xacro has
    run and resolved $(env JUPITER_GZ_PARAMS) inside the URDF itself.
    """
    import yaml
    with open(controllers_yaml, "r", encoding="utf-8") as fh:
        doc = yaml.safe_load(fh) or {}
    doc.setdefault("gazebo_ros2_control", {}).setdefault("ros__parameters", {})
    doc["gazebo_ros2_control"]["ros__parameters"]["robot_description"] = ""

    fd, path = tempfile.mkstemp(prefix="jupiter_params_", suffix=".yaml")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        yaml.safe_dump(doc, fh, default_flow_style=False, width=10 ** 9)
    return path


def _fill_urdf_into_params(path, urdf_xml):
    """Rewrite the temp params file with the real URDF embedded."""
    import yaml
    with open(path, "r", encoding="utf-8") as fh:
        doc = yaml.safe_load(fh) or {}
    doc.setdefault("gazebo_ros2_control", {}).setdefault("ros__parameters", {})
    doc["gazebo_ros2_control"]["ros__parameters"]["robot_description"] = urdf_xml
    with open(path, "w", encoding="utf-8") as fh:
        yaml.safe_dump(doc, fh, default_flow_style=False, width=10 ** 9)


def generate_launch_description():
    desc_share = get_package_share_directory("jupiterobot2_description")
    desc_prefix = get_package_prefix("jupiterobot2_description")
    gz_share = get_package_share_directory("jupiterobot2_gazebo")

    urdf_path = os.path.join(gz_share, "urdf", "jupiter2_pro.gazebo.xacro")
    controllers_yaml = os.path.join(gz_share, "config", "controllers.yaml")

    # Expand once, here. Using subprocess rather than the Command() substitution
    # means the same text can be both published on a topic and embedded in YAML.
    #
    # JUPITER_GZ_PARAMS must be in the environment BEFORE xacro runs, because
    # the xacro embeds it as $(env JUPITER_GZ_PARAMS) in the plugin block.
    params_file = _write_params_with_urdf_placeholder(controllers_yaml)
    os.environ["JUPITER_GZ_PARAMS"] = params_file

    urdf_xml = _expand_urdf(urdf_path)

    # The URDF is only known after expansion, so write the real file now and
    # leave it in place for the plugin to read.
    _fill_urdf_into_params(params_file, urdf_xml)

    # A fixed world name keeps the sim deterministic; .world.world (a previous
    # typo) made Gazebo silently fall back to an empty default world.
    world = os.path.join(gz_share, "worlds", "jupiter_empty.world")

    gazebo = ExecuteProcess(
        cmd=[
            "gazebo", "--verbose", world,
            "-s", "libgazebo_ros_init.so",
            "-s", "libgazebo_ros_factory.so",
        ],
        output="screen",
    )

    robot_state_publisher = Node(
        package="robot_state_publisher",
        executable="robot_state_publisher",
        output="screen",
        parameters=[{
            "robot_description": ParameterValue(urdf_xml, value_type=str),
            "use_sim_time": True,
        }],
    )

    spawn_entity = Node(
        package="gazebo_ros",
        executable="spawn_entity.py",
        arguments=["-topic", ROBOT_STATE_TOPIC, "-entity", "jupiter2",
                   "-timeout", "90"],
        output="screen",
    )

    spawners = [
        TimerAction(period=SPAWNER_DELAY_S, actions=[Node(
            package="controller_manager",
            executable="spawner",
            arguments=[ctrl, "--controller-manager", "/controller_manager"],
            output="screen",
        )])
        for ctrl in CONTROLLERS
    ]

    return LaunchDescription([
        SetEnvironmentVariable("GAZEBO_MODEL_PATH",
                               _build_model_path(desc_share, desc_prefix)),
        SetEnvironmentVariable("GAZEBO_MODEL_DATABASE_URI", ""),
        # The plugin must be told where the merged parameters file is. It is
        # baked into the xacro at expand time via this env var.
        SetEnvironmentVariable("JUPITER_GZ_PARAMS", params_file),
        gazebo,
        robot_state_publisher,
        spawn_entity,
    ] + spawners)
